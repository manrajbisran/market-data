#!/usr/bin/env python3
"""Turn embed/hounslow-market-embed.html into embed/market-widget.js.

The .js version lets a page use a two-line snippet, like the old provider's:

    <script src="https://cdn.jsdelivr.net/gh/manrajbisran/market-data@main/embed/market-widget.js" defer></script>
    <div class="dm-market" data-town=""></div>

Edit the .html file, then run this script to regenerate the .js.
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "embed", "hounslow-market-embed.html")
OUT = os.path.join(HERE, "..", "embed", "market-widget.js")

ROOT_LOOKUP = re.compile(
    r'  var root = document\.currentScript.*?if \(!root\) return;\n', re.S)


def main():
    html = open(SRC, encoding="utf-8").read()
    css = re.search(r"<style>\n(.*?)</style>", html, re.S).group(1)
    js = re.search(r"<script>\n\(function \(\) \{\n(.*?)\}\)\(\);\n</script>", html, re.S).group(1)
    data_src = re.search(r'data-src="([^"]+)"', html).group(1)
    js, n = ROOT_LOOKUP.subn("", js)
    if n != 1:
        raise SystemExit("Could not find the root lookup in the embed script")

    out = f"""// Generated by scripts/build_widget_js.py from embed/hounslow-market-embed.html. Do not edit.
(function () {{
  var DEFAULT_SRC = {json.dumps(data_src)};
  if (!document.getElementById("dm-market-style")) {{
    var style = document.createElement("style");
    style.id = "dm-market-style";
    style.textContent = {json.dumps(css)};
    document.head.appendChild(style);
  }}

  function init(root) {{
    if (root.getAttribute("data-dm-ready")) return;
    root.setAttribute("data-dm-ready", "1");
    if (!root.getAttribute("data-src")) root.setAttribute("data-src", DEFAULT_SRC);
    if (!root.innerHTML.trim()) root.innerHTML = '<p class="dm-loading">Loading market insights…</p>';
{js}  }}

  function initAll() {{ document.querySelectorAll(".dm-market").forEach(init); }}
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", initAll);
  else initAll();
  // Sites that change pages without a full reload (e.g. Next.js) add the block later.
  new MutationObserver(initAll).observe(document.documentElement, {{ childList: true, subtree: true }});
}})();
"""
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(out)


if __name__ == "__main__":
    main()
